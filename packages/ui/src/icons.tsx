/**
 * Every icon in the product, and the only file that knows where they come from.
 *
 * Hugeicons Stroke Rounded (ADR 0022) — the free set, and the same rounded geometry
 * Featurebase draws its duotone icons from. Moving to the Pro duotone style later is a
 * change to the imports above and nothing else.
 *
 * Each export is a component with the name a screen already uses for it, so a call site
 * reads `<Check className="size-4" />` and never learns the library's own numbering
 * (`Tick02Icon`). Sizing stays a class: the `size-*` utility overrides the width and
 * height attributes Hugeicons writes, which is what lets a button's `[&_svg]:size-4`
 * keep working.
 *
 * Each icon is imported from its own subpath rather than the package root. The root
 * re-exports twelve thousand files, and the dev server would read all of them on every
 * cold start to find these fifty.
 */
export type IconProps = Omit<HugeiconsIconProps, "icon" | "altIcon" | "showAlt">;

/** What a prop typed "an icon" accepts — `icon: Icon`. */
export type Icon = (props: IconProps) => React.JSX.Element;

function icon(svg: IconSvgElement, name: string): Icon {
  const Component = (props: IconProps) => (
    <HugeiconsIcon icon={svg} aria-hidden="true" {...props} />
  );
  Component.displayName = name;
  return Component;
}

