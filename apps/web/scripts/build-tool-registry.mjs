/**
 * Generates `src/content/tools/registry-data.ts` from the research specs.
 *
 * Run once per research refresh: `node scripts/build-tool-registry.mjs`.
 * It carries over structure only (slug, group, kind, which page sections exist, FAQ
 * count, related tools). Names here are our own plain descriptions, and no copy from
 * the research source is emitted.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const specsPath = join(here, "../../../features/free-tools/research/coachway-tool-specs.json");
const outPath = join(here, "../src/content/tools/registry-data.ts");
const specs = JSON.parse(readFileSync(specsPath, "utf8"));

const GROUP = {
  "Calories &amp; nutrition": "nutrition",
  "Strength &amp; programming": "strength",
  "Body composition": "body",
  "Heart rate &amp; cardio": "cardio",
  "For your coaching business for coaches": "business",
};

const READERS = new Set([
  "client-check-in-reader",
  "weight-trend-reader",
  "lift-progression-reader",
  "client-churn-risk-reader",
  "difficult-client-responder",
  "sales-objection-handler",
  "scope-of-practice-check",
  "coaching-business-health-check",
  "coaching-platform-fit-finder",
  "injury-exercise-swap",
]);

function kind(slug) {
  if (READERS.has(slug)) return "reader";
  if (slug === "workout-timer") return "timer";
  if (/generator|builder|checker|planner/.test(slug)) return "generator";
  return "calculator";
}

const WORDS = {
  tdee: "TDEE",
  bmr: "BMR",
  bmi: "BMI",
  ffmi: "FFMI",
  rpe: "RPE",
  rir: "RIR",
  ipf: "IPF",
  gl: "GL",
  dots: "DOTS",
  vo2: "VO2",
  ltv: "LTV",
  roi: "ROI",
  ai: "AI",
  glp1: "GLP-1",
  "1on1": "1:1",
  vs: "vs",
  instagram: "Instagram",
  navy: "Navy",
  wilks: "Wilks",
  sinclair: "Sinclair",
  cooper: "Cooper",
  keto: "Keto",
};

/** Overrides where the slug alone reads badly. Our own wording. */
const NAMES = {
  "one-rep-max-calculator": "One-rep max calculator",
  "macro-split-by-body-type-calculator": "Macro split by body type",
  "workout-plan-builder": "Workout plan builder",
  "injury-exercise-swap": "Injury exercise swap",
  "wilks-dots-calculator": "Wilks and DOTS calculator",
  "group-vs-1on1-coaching-calculator": "1:1 vs group coaching calculator",
  "no-show-cost-calculator": "No-show cost calculator",
  "personal-training-business-name-generator": "Business name generator",
  "glp1-client-coaching-planner": "GLP-1 client coaching planner",
  "zone-2-heart-rate-calculator": "Zone 2 heart rate calculator",
  "warm-up-set-calculator": "Warm-up set calculator",
  "waist-to-height-ratio-calculator": "Waist-to-height ratio calculator",
  "waist-to-hip-ratio-calculator": "Waist-to-hip ratio calculator",
  "scope-of-practice-check": "Scope-of-practice check",
  "client-check-in-builder": "Check-in builder",
  "client-check-in-reader": "Check-in reader",
  "client-churn-risk-reader": "Churn-risk reader",
};

function name(slug) {
  if (NAMES[slug]) return NAMES[slug];
  const words = slug.split("-").map((w, i) => {
    if (WORDS[w]) return WORDS[w];
    return i === 0 ? w[0].toUpperCase() + w.slice(1) : w;
  });
  return words.join(" ");
}

const ORDER = ["nutrition", "strength", "body", "cardio", "business"];
const rows = specs
  .map((s) => ({
    slug: s.slug,
    name: name(s.slug),
    group: GROUP[s.category],
    kind: kind(s.slug),
    faqCount: s.faq_count,
    sections: {
      prompt: s.has_copy_prompt,
      aiLinks: s.has_ai_research,
      demo: s.has_demo,
      sources: s.has_sources,
    },
    related: s.related_tools.filter((r) => r !== s.slug),
  }))
  .sort((a, b) => ORDER.indexOf(a.group) - ORDER.indexOf(b.group));

for (const r of rows) if (!r.group) throw new Error(`No group for ${r.slug}`);

const out = `/* Generated by scripts/build-tool-registry.mjs. Do not edit by hand: change the script. */
import type { ToolEntry } from "./types";

export const TOOL_ENTRIES: readonly ToolEntry[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(outPath, out);
console.log(`${rows.length} tools written to ${outPath}`);
